#include "ui_handler.h"                         // M5Unified.hはこの中でインクルード済

#include "flight_data.h"                        // totalFlightCountでボタンの出し分けを判定するため
#include "secrets.h"                            // AP_SSID（画面に表示するアクセスポイント名）
#include "state_machine.h"                      // wifiSetupCallerでBACKの有無を判定するため

// ============================================================
// AP接続案内画面を描画する
// ============================================================
void drawWiFiSetupGuide() {

    // 画面共通の初期化
    initScreenDrawing();

    // ------------------------------------------------------
    // タイトル
    // ------------------------------------------------------
    drawTitle("Wi-Fi SETUP");

    // ------------------------------------------------------
    // 外枠
    // ------------------------------------------------------
    drawOuterFrameWithTitle();

     // ------------------------------------------------------
    // 手順1
    // アクセスポイント名は利用者が探すべき対象のため、独立した行に黄色で強調表示する
    // ※1文字12px・外枠右端x=315のため、行頭（x=34）から23文字まで表示できる
    // ------------------------------------------------------
    M5.Lcd.setCursor(10, 40);
    M5.Lcd.print("1.");
    M5.Lcd.setCursor(34, 40);
    M5.Lcd.print("Connect your phone to");

    M5.Lcd.setCursor(34, 59);
    M5.Lcd.print("Access Point :");

    M5.Lcd.setTextColor(TFT_YELLOW);
    M5.Lcd.setCursor(34, 78);
    M5.Lcd.print(AP_SSID);
    M5.Lcd.setTextColor(TFT_WHITE);             // 以降の描画へ黄色を持ち越さないよう白へ戻す

    // ------------------------------------------------------
    // 手順2
    // 1行では画面幅（23文字）に収まらないため2行に分割している
    // ※"Follow the instructions"で終端x=310と余裕がないため、文言を伸ばす際は要再計算
    // ------------------------------------------------------
    M5.Lcd.setCursor(10, 97);
    M5.Lcd.print("2.");
    M5.Lcd.setCursor(34, 97);
    M5.Lcd.print("Follow the instructions");

    M5.Lcd.setCursor(34, 116);
    M5.Lcd.print("on the page.");

    // ------------------------------------------------------
    // ボタンラベル・区切り線（遷移元に応じて出し分け）
    // 初回起動時は戻り先がないためBACKを表示しない
    // ------------------------------------------------------
    if (wifiSetupCaller == WIFI_CALLER_INIT) {
        drawButtonLabels(nullptr, nullptr, nullptr);
    } else {
        drawButtonLabels("BACK", nullptr, nullptr);
    }
}

// ============================================================
// 接続失敗画面を描画する
// ============================================================
void drawWiFiSetupFailed() {

    // 画面共通の初期化
    initScreenDrawing();

    // ------------------------------------------------------
    // タイトル
    // ------------------------------------------------------
    drawTitle("Wi-Fi SETUP");

    // ------------------------------------------------------
    // 外枠
    // ------------------------------------------------------
    drawOuterFrameWithTitle();

    // ------------------------------------------------------
    // 失敗メッセージ
    // ------------------------------------------------------
    M5.Lcd.setCursor(10, 45);
    M5.Lcd.print("Connection failed.");

    // ------------------------------------------------------
    // ボタンラベル・区切り線（キャッシュの有無に応じて出し分け）
    // キャッシュあり：BACKで機体情報表示へ戻り、Wi-FiでAPモードへ入り直す
    // キャッシュなし：戻り先がないため、BACKはAPモードへ入り直す操作となる
    // ------------------------------------------------------
    if (totalFlightCount > 0) {
        drawButtonLabels("BACK", nullptr, "Wi-Fi");
    } else {
        drawButtonLabels("BACK", nullptr, nullptr);
    }
}

// ============================================================
// Wi-Fi接続失敗の通知画面を描画する（データ再取得時の接続失敗）
// ============================================================
void drawConnectionFailedView() {

    // 画面共通の初期化
    initScreenDrawing();

    // ------------------------------------------------------
    // 外枠
    // ------------------------------------------------------
    drawOuterFrame();

    // ------------------------------------------------------
    // 1行目（固定メッセージ）
    // ------------------------------------------------------
    M5.Lcd.setCursor(12, 15);
    M5.Lcd.print("Connection failed.");

    // ------------------------------------------------------
    // 2行目（固定メッセージ）
    // ------------------------------------------------------
    M5.Lcd.setCursor(11, 53);
    M5.Lcd.print("Change Wi-Fi settings.");

    // ------------------------------------------------------
    // ボタンラベル・区切り線
    // この画面はデータ再取得時にのみ出現し、キャッシュが必ず存在するため出し分けは行わない
    // BACK相当の動線は、Wi-Fi押下後に表示される確認ダイアログのCANCELが担う（画面遷移設計5章参照）
    // ------------------------------------------------------
    drawButtonLabels(nullptr, nullptr, "Wi-Fi");
}