/**
 * ui_handler_confirm.cpp
 * 確認ダイアログの描画処理
 */

#include "ui_handler.h"                         // M5Unified.hはこの中でインクルード済

// ============================================================
// 確認ダイアログを描画する
// ============================================================
void drawConfirmDialog(const char* title, const char* message1, const char* message2) {

    // 画面共通の初期化
    initScreenDrawing();

    // ------------------------------------------------------
    // 外枠
    // ------------------------------------------------------
    M5.Lcd.drawRect(5, 6, 310, 228, TFT_WHITE);

    // ------------------------------------------------------
    // 見出し
    // ------------------------------------------------------
    M5.Lcd.setTextSize(2);
    M5.Lcd.drawString(title, 12, 15);

    // ------------------------------------------------------
    // 詳細説明の1行目（文字小さめ）
    // ------------------------------------------------------
    M5.Lcd.setTextSize(1);
    M5.Lcd.drawString(message1, 11, 60);

    // ------------------------------------------------------
    // 詳細説明の2行目（文字小さめ、不要な場合は nullptr）
    // ------------------------------------------------------
    if (message2 != nullptr) {
        M5.Lcd.drawString(message2, 11, 84);
    }

    // ------------------------------------------------------
    // ボタンラベル・区切り線
    // ------------------------------------------------------
    M5.Lcd.setTextSize(2);
    drawButtonLabels("CANCEL", nullptr, "CONFIRM");
}