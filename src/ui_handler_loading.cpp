/**
 * ui_handler_loading.cpp
 * ローディング画面の描画処理
 */

#include "ui_handler.h"                         // M5Unified.hはこの中でインクルード済

// ============================================================
// ローディング画面を描画する
// message : 処理段階を示すメッセージ（"Connecting to Wi-Fi..." 等、5.11節参照）
// ============================================================
void drawLoadingScreen(const char* message) {

    // 画面共通の初期化
    initScreenDrawing();

    // ------------------------------------------------------
    // 外枠
    // ------------------------------------------------------
    drawOuterFrame();

    // ------------------------------------------------------
    // メッセージ（画面中央に配置。タイトルは設けない：メッセージ自体が処理内容を示すため）
    // ------------------------------------------------------
    M5.Lcd.setTextDatum(middle_center);
    M5.Lcd.drawString(message, 160, 100);
    M5.Lcd.setTextDatum(top_left);

    // ------------------------------------------------------
    // ボタンラベルエリア（操作不要な画面のため、区切り線のみでラベルは描画しない）
    // ------------------------------------------------------
    drawButtonLabels(nullptr, nullptr, nullptr);
}