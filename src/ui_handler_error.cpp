/**
 * ui_handler_error.cpp
 * エラー画面の描画処理
 */

#include "ui_handler.h"                         // M5Unified.hはこの中でインクルード済

#include "flight_data.h"                        // totalFlightCountでボタン出し分けを判定するため
#include "storage_handler.h"                    // SCAN RANGE設定値で表示するメッセージを分岐するため

// ============================================================
// エラー画面を描画する
// message : レスポンスのerror.message（またはHTTP/パースエラー時の自前文字列）
// code    : レスポンスのerror.code（同上）
// ============================================================
void drawErrorView(const char* message, const char* code) {

    // 画面共通の初期化
    initScreenDrawing();

    // ------------------------------------------------------
    // タイトル
    // ------------------------------------------------------
    drawTitle("ERROR");

    // ------------------------------------------------------
    // 上側の区切り線（外枠は使用しない。messageの折り返しが枠線を越えるため）
    // ------------------------------------------------------
    M5.Lcd.drawFastHLine(5, 34, 310, TFT_WHITE);

    // ------------------------------------------------------
    // message・code（自動折り返しあり。codeの位置はmessageの折り返し行数に応じて可変）
    // ------------------------------------------------------
    M5.Lcd.setTextWrap(true);

    M5.Lcd.setCursor(15, 40);
    M5.Lcd.printf("message : %s", message);

    int nextY = M5.Lcd.getCursorY() + 16;
    M5.Lcd.setCursor(15, nextY);
    M5.Lcd.printf("code : %s", code);

    M5.Lcd.setTextWrap(false);                                      // この画面でのみ有効化した折り返しを、他の描画に影響させないよう明示的に戻す

    // ------------------------------------------------------
    // ボタンラベル・区切り線（キャッシュの有無に応じて出し分け））
    // キャッシュなしの場合、SETTINGS経由で手詰まりにならないようRETRYも設ける
    // ------------------------------------------------------
    if (totalFlightCount > 0) {
        drawButtonLabels("BACK", nullptr, nullptr);                 // キャッシュあり（再取得時のエラー）→FLIGHT_VIEWにBACKで遷移可能
    } else {
        drawButtonLabels(nullptr, "RETRY", "SET");                  // キャッシュなし（初回設定完了後のエラー）→FLIGHT_VIEWに戻れないのでSETTINGSへ遷移後、戻ってきてRETRY
    }
}

// ============================================================
// 機体0件画面を描画する
// ============================================================
void drawNoFlightsView() {

    // 画面共通の初期化
    initScreenDrawing();

    // ------------------------------------------------------
    // 外枠
    // ------------------------------------------------------
    drawOuterFrame();

    // ------------------------------------------------------
    // 1行目（固定メッセージ）
    // ------------------------------------------------------
    M5.Lcd.setCursor(12, 15);
    M5.Lcd.print("No flights found.");

    // ------------------------------------------------------
    // 2行目（固定メッセージ）
    // ------------------------------------------------------
    M5.Lcd.setCursor(11, 53);
    M5.Lcd.print("Check settings or retry.");

    // ------------------------------------------------------
    // ボタンラベル・区切り線
    // ------------------------------------------------------
    drawButtonLabels(nullptr, "RETRY", "SET");
}