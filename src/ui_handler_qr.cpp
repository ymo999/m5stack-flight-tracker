/**
 * ui_handler_qr.cpp
 * 設定画面へのQRコード誘導画面（APIキー設定／基準地点設定）の描画処理
 */

#include "ui_handler.h"         // M5Unified.hはこの中でインクルード済

#include <WiFi.h>               // WiFi.localIP()でアクセス先URLを生成するため

// ============================================================
// 設定画面へのQRコード誘導画面を描画する（共通関数）
// タイトルのみ中央揃え、他の要素はすべて左揃え（drawWiFiSetupGuide()と同じ方針）
// ============================================================
void drawSetupQRScreen(const char* title, const char* path, const char* extraInfo,
                        const char* statusMsg, const char* buttonLabel) {
    
    // 画面共通の初期化
    initScreenDrawing();

    // ------------------------------------------------------
    // タイトル
    // ------------------------------------------------------
    drawTitle(title);

    // ------------------------------------------------------
    // 外枠
    // ------------------------------------------------------
    drawOuterFrameWithTitle();

    // ------------------------------------------------------
    // アクセス先URLを動的に生成（stationモードで接続中のIPアドレスを使用）
    // ------------------------------------------------------
    String url = "http://" + WiFi.localIP().toString() + String(path);

    // ------------------------------------------------------
    // QRコード（中央付近に描画。M5GFX組み込みのqrcode描画機能を使用）
    // サイズは110px
    // ------------------------------------------------------
    M5.Lcd.qrcode(url.c_str(), 105, 40, 110, 3);

    // ------------------------------------------------------
    // ステータスメッセージ（黄色・左揃え）
    // ------------------------------------------------------
    if (statusMsg != nullptr) {
        M5.Lcd.setTextSize(1);
        M5.Lcd.setTextColor(TFT_YELLOW);
        M5.Lcd.setCursor(18, 160);
        M5.Lcd.print(statusMsg);
        M5.Lcd.setTextColor(TFT_WHITE);             // 以降の描画へ黄色を持ち越さないよう白へ戻す
    }

    // ------------------------------------------------------
    // 共通の案内文（左揃え）
    // ------------------------------------------------------
    M5.Lcd.setTextSize(1);
    M5.Lcd.setCursor(18, 170);
    M5.Lcd.print("Connect to the same Wi-Fi, then scan");

    // ------------------------------------------------------
    // URL（左揃え）
    // ------------------------------------------------------
    M5.Lcd.setTextSize(1);                          // 画面に収まらなくなるためフォントサイズ変更
    M5.Lcd.setCursor(18, 180);
    M5.Lcd.print(url);

    // ------------------------------------------------------
    // 現在の設定値（基準地点設定の場合のみ）
    // ------------------------------------------------------
    if (extraInfo != nullptr) {
        M5.Lcd.setTextSize(1);
        M5.Lcd.setTextColor(TFT_WHITE);
        M5.Lcd.setCursor(18, 192);
        M5.Lcd.print(extraInfo);
    }

    // ------------------------------------------------------
    // ボタンラベル・区切り線（nullptr なら非表示）
    // ------------------------------------------------------
    drawButtonLabels(buttonLabel, nullptr, nullptr);
}